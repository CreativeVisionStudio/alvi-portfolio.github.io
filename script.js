// Whole website language switch: English <-> Bangla.
const languageToggle = $('languageToggle');
const textNodes = [];
const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
  acceptNode(node) {
    if (!node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
    const parent = node.parentElement;
    if (!parent || parent.closest('script,style,button#languageToggle')) return NodeFilter.FILTER_REJECT;
    return NodeFilter.FILTER_ACCEPT;
  }
});
while (walker.nextNode()) {
  const node = walker.currentNode;
  textNodes.push({ node, original: node.nodeValue, key: node.nodeValue.trim() });
}
function setLanguage(language) {
  const bangla = language === 'bn';
  textNodes.forEach(item => {
    if (!item.node.isConnected) return;
    const translated = translations[item.key];
    item.node.nodeValue = bangla && translated
      ? item.original.replace(item.key, translated)
      : item.original;
  });
  document.documentElement.lang = bangla ? 'bn' : 'en';
  document.body.classList.toggle('bangla', bangla);
  if (languageToggle) {
    languageToggle.textContent = bangla ? 'EN' : 'বাং';
    languageToggle.setAttribute('aria-label', bangla ? 'Switch website to English' : 'ওয়েবসাইট বাংলায় দেখুন');
    languageToggle.title = bangla ? 'Switch to English' : 'বাংলা ভাষায় দেখুন';
  }
  document.title = bangla ? 'আলভি রহমান | ওয়েব ডেভেলপার ও গ্রাফিক্স ডিজাইনার' : 'Alvi Rahman | Web Developer & Graphics Designer';
  try { localStorage.setItem('alvi-language', language); } catch (_) {}
}
let savedLanguage = 'en';
try { savedLanguage = localStorage.getItem('alvi-language') || 'en'; } catch (_) {}
setLanguage(savedLanguage);
if (languageToggle) languageToggle.addEventListener('click', () => {
  setLanguage(document.documentElement.lang === 'bn' ? 'en' : 'bn');
});


// Contact form: requires a public Formspree endpoint ID in index.html.
const contactForm = $('contactForm');
if (contactForm) {
  const submitButton = $('contactSubmit');
  const formStatus = $('formStatus');
  const defaultButtonText = submitButton ? submitButton.innerHTML : '';
  const currentLanguage = () => document.documentElement.lang === 'bn' ? 'bn' : 'en';
  const formMessages = {
    en: {
      sending: 'Sending your message…',
      success: 'Message sent successfully. Thank you!',
      invalid: 'Please complete all fields with a valid email address.',
      setup: 'Contact form setup is not finished yet. Please email me directly for now.',
      error: 'Sorry, your message could not be sent. Please try again or email me directly.'
    },
    bn: {
      sending: 'আপনার বার্তা পাঠানো হচ্ছে…',
      success: 'বার্তা সফলভাবে পাঠানো হয়েছে। ধন্যবাদ!',
      invalid: 'সব ঘর পূরণ করুন এবং সঠিক ইমেইল ঠিকানা দিন।',
      setup: 'যোগাযোগ ফর্মের সেটআপ এখনো সম্পূর্ণ হয়নি। আপাতত সরাসরি ইমেইল করুন।',
      error: 'দুঃখিত, বার্তা পাঠানো যায়নি। আবার চেষ্টা করুন অথবা সরাসরি ইমেইল করুন।'
    }
  };
  contactForm.addEventListener('submit', async (event) => {
    event.preventDefault();
    const lang = currentLanguage();
    const messages = formMessages[lang];
    if (!contactForm.reportValidity()) {
      if (formStatus) formStatus.textContent = messages.invalid;
      return;
    }
    const endpoint = contactForm.dataset.endpoint || '';
    if (!/^https:\/\/formspree\.io\/f\/[A-Za-z0-9]+$/.test(endpoint) || endpoint.endsWith('/YOUR_FORM_ID')) {
      if (formStatus) formStatus.textContent = messages.setup;
      return;
    }
    if (submitButton) {
      submitButton.disabled = true;
      submitButton.textContent = messages.sending;
    }
    if (formStatus) formStatus.textContent = messages.sending;
    try {
      const response = await fetch(endpoint, {
        method: 'POST',
        body: new FormData(contactForm),
        headers: { Accept: 'application/json' }
      });
      if (!response.ok) throw new Error('Form submission failed');
      contactForm.reset();
      if (formStatus) formStatus.textContent = messages.success;
    } catch (error) {
      if (formStatus) formStatus.textContent = messages.error;
    } finally {
      if (submitButton) {
        submitButton.disabled = false;
        submitButton.innerHTML = defaultButtonText;
      }
    }
  });
}

